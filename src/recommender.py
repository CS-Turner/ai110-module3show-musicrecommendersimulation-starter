def load_songs(csv_path: str) -> List[Dict]:
    """Load songs from a CSV file into dicts with numeric fields converted."""
    songs = []
    with open(csv_path, newline="", encoding="utf-8") as f:
        for row in csv.DictReader(f):
            row["id"] = int(row["id"])
            row["tempo_bpm"] = float(row["tempo_bpm"])
            for key in ("energy", "valence", "danceability", "acousticness"):
                row[key] = float(row[key])
            songs.append(row)
    return songs


def score_song(user_prefs: Dict, song: Dict) -> Tuple[float, List[str]]:
    """Score one song out of 10 and return the score with reasons."""
    score = 0.0
    reasons = []

    if song["genre"].lower() == user_prefs["favorite_genre"].lower():
        score += 4.0
        reasons.append("genre match (+4.0)")
    if song["mood"].lower() == user_prefs["favorite_mood"].lower():
        score += 3.0
        reasons.append("mood match (+3.0)")

    energy_pts = 2.0 * (1 - abs(song["energy"] - user_prefs["target_energy"]))
    score += energy_pts
    reasons.append(f"energy closeness (+{energy_pts:.2f})")

    if user_prefs["likes_acoustic"]:
        acoustic_pts = song["acousticness"]
    else:
        acoustic_pts = 1 - song["acousticness"]
    score += acoustic_pts
    reasons.append(f"acousticness fit (+{acoustic_pts:.2f})")

    return score, reasons


def recommend_songs(user_prefs: Dict, songs: List[Dict], k: int = 5) -> List[Tuple[Dict, float, str]]:
    """Score every song and return the top k as (song, score, explanation)."""
    scored = []
    for song in songs:
        score, reasons = score_song(user_prefs, song)
        scored.append((song, score, "; ".join(reasons)))
    return sorted(scored, key=lambda item: item[1], reverse=True)[:k]
